create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin');
$$;
revoke all on function private.is_admin() from public, anon, authenticated;
grant execute on function private.is_admin() to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare r public.user_role;
begin
  r := case when new.raw_user_meta_data->>'role'='chofer' then 'chofer'::public.user_role else 'usuario'::public.user_role end;
  insert into public.profiles(id,role,full_name,email)
  values(new.id,r,coalesce(new.raw_user_meta_data->>'full_name',''),new.email)
  on conflict (id) do nothing;
  if r='chofer' then insert into public.drivers(id) values(new.id) on conflict do nothing; end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.civimoto_distance_km(lat1 double precision, lon1 double precision, lat2 double precision, lon2 double precision)
returns numeric
language sql
immutable
as $$
  select round((6371 * 2 * asin(sqrt(
    power(sin(radians(lat2-lat1)/2),2) +
    cos(radians(lat1))*cos(radians(lat2))*power(sin(radians(lon2-lon1)/2),2)
  )))::numeric,2);
$$;

create or replace function public.request_civimoto_trip(
  p_origin_address text,p_origin_lat double precision,p_origin_lng double precision,
  p_destination_address text,p_destination_lat double precision,p_destination_lng double precision,
  p_payment_method text default 'efectivo'
) returns public.trips
language plpgsql
security invoker
set search_path = public
as $$
declare d numeric; f numeric; fare_row public.fares%rowtype; out_trip public.trips%rowtype;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión'; end if;
  if not exists(select 1 from public.profiles where id=auth.uid() and role='usuario' and account_status='activo') then raise exception 'Cuenta de pasajero no disponible'; end if;
  if exists(select 1 from public.trips where passenger_id=auth.uid() and status in ('solicitado','aceptado','chofer_en_camino','chofer_llego','en_viaje')) then raise exception 'Ya tienes un viaje activo'; end if;
  select * into fare_row from public.fares where active=true order by created_at desc limit 1;
  d := public.civimoto_distance_km(p_origin_lat,p_origin_lng,p_destination_lat,p_destination_lng);
  f := greatest(coalesce(fare_row.minimum_fare,5), coalesce(fare_row.base_fare,3) + d*coalesce(fare_row.per_km,1.5));
  insert into public.trips(passenger_id,origin_address,origin_lat,origin_lng,destination_address,destination_lat,destination_lng,estimated_distance_km,estimated_fare,payment_method)
  values(auth.uid(),coalesce(nullif(trim(p_origin_address),''),'Mi ubicación'),p_origin_lat,p_origin_lng,coalesce(nullif(trim(p_destination_address),''),'Destino'),p_destination_lat,p_destination_lng,d,round(f,2),case when lower(p_payment_method)='yape' then 'yape' else 'efectivo' end)
  returning * into out_trip;
  return out_trip;
end;
$$;

grant execute on function public.request_civimoto_trip(text,double precision,double precision,text,double precision,double precision,text) to authenticated;

create or replace function public.accept_civimoto_trip(p_trip_id uuid)
returns public.trips
language plpgsql
security invoker
set search_path=public
as $$
declare out_trip public.trips%rowtype;
begin
  if not exists(select 1 from public.drivers where id=auth.uid() and status='aprobado' and is_available=true) then raise exception 'Chofer no disponible o no aprobado'; end if;
  update public.trips set driver_id=auth.uid(),status='aceptado',accepted_at=now()
  where id=p_trip_id and status='solicitado' and driver_id is null
  returning * into out_trip;
  if out_trip.id is null then raise exception 'El servicio ya fue tomado'; end if;
  return out_trip;
end;
$$;
grant execute on function public.accept_civimoto_trip(uuid) to authenticated;

create or replace function public.driver_set_live_location(p_lat double precision,p_lng double precision,p_heading double precision default null,p_speed_kmh double precision default null)
returns public.driver_live_locations
language plpgsql
security invoker
set search_path=public
as $$
declare out_row public.driver_live_locations%rowtype;
begin
  if not exists(select 1 from public.drivers where id=auth.uid()) then raise exception 'Solo chofer'; end if;
  insert into public.driver_live_locations(driver_id,lat,lng,heading,speed_kmh,updated_at)
  values(auth.uid(),p_lat,p_lng,p_heading,p_speed_kmh,now())
  on conflict(driver_id) do update set lat=excluded.lat,lng=excluded.lng,heading=excluded.heading,speed_kmh=excluded.speed_kmh,updated_at=now()
  returning * into out_row;
  return out_row;
end;
$$;
grant execute on function public.driver_set_live_location(double precision,double precision,double precision,double precision) to authenticated;

create or replace function public.driver_update_civimoto_trip(p_trip_id uuid,p_status public.trip_status)
returns public.trips
language plpgsql
security invoker
set search_path=public
as $$
declare t public.trips%rowtype;
begin
  select * into t from public.trips where id=p_trip_id and driver_id=auth.uid() for update;
  if t.id is null then raise exception 'Viaje no encontrado'; end if;
  if p_status='chofer_en_camino' and t.status='aceptado' then null;
  elsif p_status='chofer_llego' and t.status='chofer_en_camino' then null;
  elsif p_status='en_viaje' and t.status in ('chofer_llego','aceptado') then null;
  elsif p_status='completado' and t.status='en_viaje' then null;
  elsif p_status='cancelado' and t.status in ('aceptado','chofer_en_camino','chofer_llego') then null;
  else raise exception 'Transición de estado inválida'; end if;
  update public.trips set status=p_status,
    started_at=case when p_status='en_viaje' then coalesce(started_at,now()) else started_at end,
    completed_at=case when p_status='completado' then now() else completed_at end,
    final_fare=case when p_status='completado' then coalesce(final_fare,estimated_fare) else final_fare end
  where id=p_trip_id returning * into t;
  return t;
end;
$$;
grant execute on function public.driver_update_civimoto_trip(uuid,public.trip_status) to authenticated;

create or replace function public.passenger_cancel_civimoto_trip(p_trip_id uuid,p_reason text default 'Cancelado por pasajero')
returns public.trips
language plpgsql
security invoker
set search_path=public
as $$
declare t public.trips%rowtype;
begin
  update public.trips set status='cancelado',cancellation_reason=left(coalesce(p_reason,'Cancelado por pasajero'),300)
  where id=p_trip_id and passenger_id=auth.uid() and status in ('solicitado','aceptado','chofer_en_camino','chofer_llego')
  returning * into t;
  if t.id is null then raise exception 'El viaje ya no puede cancelarse'; end if;
  return t;
end;
$$;
grant execute on function public.passenger_cancel_civimoto_trip(uuid,text) to authenticated;

