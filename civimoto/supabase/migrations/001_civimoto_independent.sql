create table public.fares (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'Tarifa general',
  base_fare numeric(10,2) not null default 3.00,
  per_km numeric(10,2) not null default 1.50,
  per_minute numeric(10,2) not null default 0.00,
  minimum_fare numeric(10,2) not null default 5.00,
  platform_commission_percent numeric(5,2) not null default 0.00,
  active boolean not null default true,
  created_at timestamptz not null default now()
