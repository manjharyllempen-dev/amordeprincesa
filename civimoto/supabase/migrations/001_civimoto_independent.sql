create extension if not exists pgcrypto;

create type public.user_role as enum ('usuario','chofer','admin');
create type public.driver_status as enum ('pendiente','aprobado','rechazado','suspendido');
create type public.trip_status as enum ('solicitado','aceptado','chofer_en_camino','chofer_llego','en_viaje','completado','cancelado');
create type public.billing_period as enum ('semanal','mensual');
create type public.payment_status as enum ('pendiente','aprobado','rechazado');

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.user_role not null default 'usuario',
  full_name text not null default '',
  phone text,
  email text,
  avatar_url text,
  rating numeric(3,2) not null default 5.00 check (rating between 1 and 5),
  account_status text not null default 'activo' check (account_status in ('activo','suspendido')),
  suspended_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.drivers (
  id uuid primary key references public.profiles(id) on delete cascade,
  status public.driver_status not null default 'pendiente',
  document_number text,
  license_number text,
  is_available boolean not null default false,
  rating numeric(3,2) not null default 5.00 check (rating between 1 and 5),
  approved_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.vehicles (
  id uuid primary key default gen_random_uuid(),
